-- Additive shift ledger. Existing business days remain legacy records; only
-- newly opened rows with report_version=1 produce a cashier shift report.
alter table business_days
  add column if not exists shift_number bigint generated by default as identity,
  add column if not exists starting_cash numeric(12,2),
  add column if not exists report_version integer,
  add column if not exists closing_at timestamptz,
  add column if not exists shift_report jsonb;

create unique index if not exists business_days_one_open_shift
  on business_days ((true)) where closed_at is null and report_version = 1;

alter table cash_expenses
  add column if not exists business_day_id uuid references business_days(id) on delete restrict;
create index if not exists cash_expenses_shift_idx on cash_expenses(business_day_id, created_at);

create table if not exists shift_cash_movements (
  id uuid primary key default gen_random_uuid(),
  business_day_id uuid not null references business_days(id) on delete restrict,
  kind text not null check (kind in ('paid_in', 'owner_transfer', 'cash_refund')),
  purpose text not null check (length(trim(purpose)) > 0),
  amount numeric(12,2) not null check (amount > 0),
  transaction_id uuid references transactions(id) on delete restrict,
  recorded_by uuid not null references profiles(id) on delete restrict,
  created_at timestamptz not null default now(),
  constraint refund_transaction_required check ((kind = 'cash_refund') = (transaction_id is not null))
);
create unique index if not exists shift_cash_refund_once
  on shift_cash_movements(transaction_id) where kind = 'cash_refund';
create index if not exists shift_cash_movements_shift_idx
  on shift_cash_movements(business_day_id, created_at);
alter table shift_cash_movements enable row level security;

create or replace function assert_shift_cash_entry_open() returns trigger language plpgsql as $$
declare v_shift business_days%rowtype;
begin
  if new.business_day_id is null then return new; end if;
  select * into v_shift from business_days where id = new.business_day_id for update;
  if not found or v_shift.closed_at is not null or v_shift.closing_at is not null then
    raise exception 'Shift is closing or already closed';
  end if;
  return new;
end;
$$;

create trigger shift_movement_open_guard before insert on shift_cash_movements
  for each row execute function assert_shift_cash_entry_open();
create trigger shift_expense_open_guard before insert on cash_expenses
  for each row execute function assert_shift_cash_entry_open();
